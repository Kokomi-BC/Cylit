"""第二阶段「论文理解」提示词：**两路做不同的事**，且与翻译/转录提示词完全分开。

用户口径（逐条对应）：

- ⑤ 理解是**第二阶段**：必须在翻译/转写完成之后再注入**新的**理解提示词，
  绝不能把"理解"塞进翻译提示词里（那会让翻译同时干两件事，两边都变差）。
- ⑥ 两路做**不同**的理解任务：A 路（英文转录侧）做**技术解剖**，
  B 路（中文翻译侧）做**阅读地图 + 相关概念**。
- ⑦ 结果**不是固定 schema**：自由 Markdown，模型可以增删合并小节；
  这里只约定"要覆盖哪些**方面**"，不约定小节标题与小节数量。
- ⑧ **相关概念必须由中文路（B）产出**，并引用它自己的 chunk 短码。
- ④ chunk 是理解的**引用基准单位**：引用写成 `来源 Chunk: B023`。

关于"能不能用通用知识"：两条路的理解阶段都**允许并且鼓励**动用通用知识补齐背景
（用户明确选了这一口径），因此提示词里**不要求区分"论文里说的"与"通用知识"**。
知识库问答（`rag_service`）相反，仍然严格"只依据来源"，两者不共享这段规则。
"""

from __future__ import annotations

#: 两路共用的"引用与输出格式"约定
_SHARED = """【引用规则（硬要求）】
1. 清单里每条材料都有一个**短码**（A 路形如 `A012`、B 路形如 `B023`）。引用论文里的具体内容时，
   必须在句末用 `（来源 Chunk: 短码）` 的形式标出来，例如：
   `TURBOQUANT 用两阶段量化器消除内积偏差（来源 Chunk: B023）。`
2. **只许引用清单里出现过的短码**。清单里没有的内容不要编短码 —— 编出来的引用会被系统丢弃，
   还会让整条结果被标记为"引用不可信"。
3. 一段话依据多条材料时把短码都列上：`（来源 Chunk: B023, B031）`。
4. 短码是**本路**的编号（A 路只有 `A…`、B 路只有 `B…`），不要跨路引用。

【输出格式】
先输出一段**自由 Markdown**，再输出一个 JSON 收尾，形如：

<自由 Markdown，随便你怎么组织小节；系统不会按固定 schema 校验>
```json
{"refs": ["B023", "B031"]}
```

- `refs` 是你**实际引用过**的短码去重列表（用来做校验与"跳转到原文"）。
- Markdown 部分**不要套固定模板**：小节标题、数量、顺序都由你按这篇论文的内容决定，
  该合并就合并、该删就删。**不要为了凑模板写空话**。
- 允许使用数学公式（`$…$` / `$$…$$`）、表格、列表。公式要与论文一致。
"""

#: A 路：技术解剖（读者 = 想复现/评估这项工作的人）
UNDERSTAND_A_SYSTEM = f"""你是一位严谨的技术审稿人。下面给你的是**同一篇论文**的英文材料清单
（按论文顺序排列的语义单元 / 公式 / 图 / 表，每条的短码在行首）。
请对这篇论文做一次**技术解剖**，让读者不必翻原文就能判断"这项工作成不成立、能不能复现"。

【必须覆盖的方面（**方面**，不是小节标题；怎么组织由你决定）】
- **问题与假设**：要解决什么、在什么假设下成立；假设被明确写出来的就引用它。
- **方法链条**：方法的每一步在做什么、为什么这么做、与上一步的关系。
- **公式与符号**：关键公式的**作用**（不是抄一遍）、符号含义、以及它在方法里处在哪一环。
- **正确性**：定理/引理在说什么、证明走的是哪条路（骨架即可）；界/近似是怎么来的。
- **实验**：数据集、基线、指标、主要结论；哪些结论是实验支撑的、哪些只是声称。
- **复现要点**：要复现需要哪些关键步骤、超参、容易踩的坑。
- **局限与可疑之处**：你自己判断出来的弱点（允许用通用知识判断，**不必区分来源**）。

{_SHARED}"""

#: B 路：阅读地图 + 相关概念（读者 = 第一次读这篇论文的人）
UNDERSTAND_B_SYSTEM = f"""你是一位很会带人读论文的老师。下面给你的是**同一篇论文**的中文材料清单
（按论文顺序排列的语义单元 / 公式 / 图 / 表，每条的短码在行首）。
请写一份**阅读地图**，让一个第一次接触这个方向的人知道"这篇论文在讲什么、该怎么读"。

【必须覆盖的方面（**方面**，不是小节标题；怎么组织由你决定）】
- **一句话概括**：这篇论文做了什么、解决了什么痛点。
- **相关概念（先写这一节** —— 这是整份理解里**最重要**的产出，实测放在最后会被输出长度截掉）**：
  挑出 4~8 个理解这篇论文**真正需要**的概念，每个概念写成一个小节，包含：
  1. 概念名（中英文都写）；
  2. **2~4 句解释**：它是什么、为什么这里需要它；
  3. 它在这篇论文里的**具体作用**；
  4. **来源 Chunk 引用**（必须引用**本路的短码**，每个概念至少一条）。
  概念可以超出论文本身（允许通用知识与外部背景），但**每条都必须给出本路的短码引用**，
  指向论文里用到它的那段材料。
- **推荐阅读顺序**：先读哪几节、哪些可以跳读、为什么；把正文路线串成一条线。
- **读之前需要知道的**：前置知识、术语、记号（读者不具备时可以直接补通用背景知识，
  **不必区分是论文说的还是通用知识**）。
- **难点**：哪里最容易卡住、卡住时应该回头看哪一段。
- **与其他工作的关系**：论文自己提到的对比/继承关系。

{_SHARED}"""


def system_for(path: str) -> str:
    """按路取 system prompt（``a`` = 技术解剖、``b`` = 阅读地图）。"""
    if path == "a":
        return UNDERSTAND_A_SYSTEM
    if path == "b":
        return UNDERSTAND_B_SYSTEM
    raise ValueError(f"未知的路径：{path!r}（只支持 'a' / 'b'）")


#: 材料清单里每条的最大预览字数（控制 prompt 体积；引用靠短码，不靠原文）
PREVIEW_CHARS = 220


def render_understanding_prompt(*, path: str, title: str, inventory: list[dict],
                                brief: str = "") -> str:
    """渲染一次理解调用的 user prompt。

    `inventory` 每项：``{"code","chunk_type","page","section","preview"}``（见
    `understanding_service.chunk_inventory`）。**只给短码与预览**：理解阶段要的是
    "看懂了再讲"，把全文塞进去只会让它抄原文。
    """
    label = "英文材料清单（A 路：原文转录）" if path == "a" else "中文材料清单（B 路：中文译文）"
    lines = [f"【论文】{title}", f"【{label}】共 {len(inventory)} 条，按论文顺序：", ""]
    for item in inventory:
        head = f"[{item['code']}] {item['chunk_type']}"
        if item.get("page"):
            head += f" p{item['page']}"
        if item.get("section"):
            head += f" · {item['section']}"
        lines.append(head)
        preview = (item.get("preview") or "").strip().replace("\n", " ")
        if preview:
            lines.append(f"    {preview[:PREVIEW_CHARS]}")
    if brief:
        lines += ["", "【文档简报（术语与主题，供参考）】", brief]
    lines += ["", "请按 system 里的要求输出：先自由 Markdown，最后用一个 ```json 代码块给出 refs。"]
    return "\n".join(lines)
