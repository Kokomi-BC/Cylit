"""第二阶段「论文理解」提示词：**与翻译/转录提示词完全分开**。

用户口径（逐条对应）：

- ⑤ 理解是**第二阶段**：必须在翻译/转写完成之后再注入**新的**理解提示词，
  绝不能把"理解"塞进翻译提示词里（那会让翻译同时干两件事，两边都变差）。
- ⑥ 理解做的是**论文精读**（基本信息 → 背景与问题 → 动机与 gap → **贡献与创新点** →
  方法 → 实验 → 结论、局限与启发）。原先的"技术解剖"被判定与「阅读地图」重复，
  换成了上面这套精读框架（把用户点名要的**论文创新点**放在这一路）。
  2026-10-02 用户口径：**「阅读地图 + 相关概念」整条删除**（前端入口与后端提示词/任务一起清掉），
  那条模型能力转去做**论文元数据生成与填写**（`services/paper/metadata_fill.py`）。
- ⑦ 结果**不是固定 schema**：自由 Markdown，模型可以增删合并小节；
  这里只约定"要覆盖哪些**方面**"，不约定小节标题与小节数量。
- ④ chunk 是理解的**引用基准单位**，但正文里只写它的**编号**：`[A023]`
  （旧写法 `（来源 Chunk: A023）` 已废 —— 见 `_SHARED` 的注释）。

关于"能不能用通用知识"：理解阶段**允许并且鼓励**动用通用知识补齐背景
（用户明确选了这一口径），因此提示词里**不要求区分"论文里说的"与"通用知识"**。
知识库问答（`rag_service`）相反，仍然严格"只依据来源"，两者不共享这段规则。
"""

from __future__ import annotations

#: "引用与输出格式"约定
#:
#: 引用标记**只有编号本身**（`[A023]`）。2026-11-28 用户口径：正文里不要再出现
#: "Chunk" 这个字 —— 旧写法 `（来源 Chunk: A023）` 是给机器看的，读者看到的是
#: 一坨实现词汇。编号留成 `[A023]` 是**人能点的那一枚**（前端渲染成序号的跳转标号），
#: 「来源」「出处」这类字一个字都不必写。
#:
#: 为什么编号带字母前缀：正文里 `[2, 4]` 是**参考文献**标号（`useMarkdown` 的
#: cite 扩展把它接成参考文献浮层），材料编号必须是另一套形状，否则两者会互相顶。
_SHARED = """【引用标记（硬要求）】
1. 清单里每条材料行首有一个**编号**（形如 `A012`，系统用它定位到原文那一段）。
   正文里凡是依据某一条材料的句子，在**句末紧跟**方括号编号，例如：
   `TURBOQUANT 用两阶段量化器消除内积偏差[A023]。`
2. **只许用清单里出现过的编号**。清单里没有的不要编 —— 编出来的标记会被系统丢弃，
   还会让整条结果被标记为"引用不可信"。
3. 一句话依据多条材料就并排写：`[A023][A031]`。
4. 正文里**只出现编号本身**：不要写"来源""出处""据…所述"，也不要写任何系统内部词汇
   （分块、检索清单、材料编号表之类），更不要另起一段列参考文献 ——
   读者点那个编号就直接跳到原文那一段，多写的字全是噪音。

【插图（可选，但很有用）】
1. 清单里标了「〔可插入的图：img:A012〕」的条目，才是**能显示**的插图 / 表格裁图；
   没标的一律贴不出来（正文段落、多数公式条目如此）。
2. 想在某处展示它，就**单独起一行**写 Markdown 图片，地址只写那个短码，例如：
   `![图 1：不同层类型的最大路径长度、每层复杂度与最少顺序操作数](img:A012)`
   方括号里写**图注本身**（读者看到的就是这一句），不要写"见下图""如上图所示"这类空话。
3. 只在**这张图确实支撑你正在讲的那一点**时才插（讲表 1 的复杂度对比 → 贴表 1 那张）；
   一篇 3~6 张足够，同一张不要重复贴；图片前面先用一句话说清它要说明什么。
4. 除 `img:` 短码以外的地址（http 链接、文件路径、别的编号）一律不要写 —— 系统只认短码。

【输出格式】
先输出一段**自由 Markdown**，再输出一个 JSON 收尾，形如：

<自由 Markdown，随便你怎么组织小节；系统不会按固定 schema 校验>
```json
{"refs": ["A023", "A031"]}
```

- `refs` 是你**实际引用过**的编号去重列表（用来做校验与"跳转到原文"）。
- Markdown 部分**不要套固定模板**：小节标题、数量、顺序都由你按这篇论文的内容决定，
  该合并就合并、该删就删。**不要为了凑模板写空话**。
- 允许使用数学公式（`$…$` / `$$…$$`）、表格、列表。公式要与论文一致。
"""

#: 论文精读（读者 = 想快速抓住"这是什么论文、新在哪、能不能站住"的人）
UNDERSTAND_A_SYSTEM = f"""你是一位很会带人读论文的老师。下面给你的是**同一篇论文**的英文材料清单
（按论文顺序排列的段落 / 公式 / 图 / 表，每条的编号在行首）。
请写一份**论文精读**，让读者不必翻原文就能说清"这是一篇什么论文、它新在哪、能不能站住"。

【先判类型，再决定看什么】
先认出这是**实验类 / 计算与模拟 / 生信 / 临床与观察 / 方法学 / 综述**里的哪一种，按类型调整重点：
- 实验类：自变量、因变量、对照、重复与误差先看，再看结果；
- 计算与模拟：模型假设、数据集与划分、基线选择、消融、算力预算；外推到真实数据前先问假设成不成立；
- 生信：数据来源与预处理、批次效应、多重检验校正、验证集是否独立；
- 临床与观察：入排标准、终点定义、随访时长、混杂控制、效应量与置信区间；观察性研究不谈因果；
- 方法学：与最强基线的比较是否公平、收益到底从哪来（消融能不能解释）、适用边界在哪；
- 综述：不套自变量与因变量，改看检索与纳入逻辑、证据范围、主题分类、争议点与未解决问题。

【硬规则（比下面的框架更重要）】
1. **数值只能来自材料**：材料没给的数字不许猜；图里读不准就写「趋势可见，精确值读不出」。
   会议 / 期刊分区、影响因子这类外部指标材料里没有就不写，更不许凭记忆填。
2. **论文没说的地方别讲得跟原文一样**：由你判断的内容（机制、动机、隐含假设）用「据…推断」
   「可能是」这类说法，不许与原文事实混在一起讲，也不许把作者的措辞当成事实。
3. **结论强度跟着证据走**：相关性不写成因果，proxy 不写成直接测量，仿真不写成实验验证。
4. **每条关键结论都说清它「能证明什么、不能证明什么」**，并一句话给出证据强弱的理由。
5. **方法要绑定目的**：不只写"用了什么方法"，每个方法都要说清它在证据链里负责验证什么。
6. 材料里的预览被截断只是省篇幅，**不要**据此说「材料缺失 / 数值被截断 / 无法核验」。

【大致框架（**是顺序建议，不是固定模板**：该合并就合并、该增删就增删，小节标题与数量由你定）】
- **基本信息**：标题 / 作者与机构 / 发表会议或期刊与年份 / 领域与关键词。
- **背景与问题**：这个方向此前做到哪一步、这篇论文要解决的具体问题是什么。
- **动机与 gap**：作者为什么认为现有做法不够（gap 到底是什么），他们的洞察是什么。
- **贡献与创新点**：**逐条**写清楚这篇论文的贡献，每条都要说清"**相对已有工作新在哪**"——
  是新的目标函数、新的算法步骤、新的理论界、新的实验结论，还是新的系统/工程做法。
  **不要把"我们提出了 X"照抄一遍**：要写清 X 为什么算新、与最接近的做法差在哪。
- **方法**：方法链条一步步在做什么、每一步为什么这么做、关键公式的**作用**（不是抄一遍）
  与符号含义、以及它在方法里处在哪一环。
- **实验与证据**：数据集 / 基线 / 指标 / 主要结论；哪些结论是实验支撑的、哪些只是声称。
  关键图**只深读支撑核心结论的那几张**：各写清它支撑哪条主张、以及这张图**不能**支持什么（不要逐张复述）。
- **结论、局限与启发**：作者的结论、你自己判断出来的弱点与边界条件，以及这项工作对后续研究或
  工程落地的启发（允许用通用知识判断、**不必区分来源**，但推出来的话要让人看得出是推的）。
  这一节收尾回答两句：**如果只能留三张图，留哪三张、为什么**；**如果你来审这篇稿，最希望作者补的
  三项实验 / 分析 / 验证是什么**（每项点明它排除了哪种替代解释、补齐哪条证据链）。
- **复现要点**（可选）：要复现需要哪些关键步骤、超参、容易踩的坑。

{_SHARED}"""


def system_for(path: str = "a") -> str:
    """取 system prompt。现在只有一路（``a`` = 论文精读）。

    ``path`` 参数保留：任务、模板、日志里都还带着它，删掉只会让调用点处处改签名。
    """
    if path in ("a", "", None):
        return UNDERSTAND_A_SYSTEM
    raise ValueError(f"未知的路径：{path!r}（只支持 'a'）")


#: 材料清单里每条的最大预览字数（控制 prompt 体积；引用靠短码，不靠原文）
PREVIEW_CHARS = 220
#: 表格/公式条目给**全文**（上限）：它们的价值全在数值与公式本身，预览只剩表头没有数值，
#: 模型会据此说"材料中表格数值被截断，无法核验提升是否显著"（2026-09-27 用户报的）。
RICH_CHARS = 2200


def render_understanding_prompt(*, path: str = "a", title: str, inventory: list[dict],
                                brief: str = "", head: str = "",
                                task_block: str = "") -> str:
    """渲染一次理解调用的 user prompt。

    `inventory` 每项：``{"code","chunk_type","page","section","preview"[,"content"]}``
    （见 `understanding_service.chunk_inventory`；表格/公式带全文 `content`）。

    `head`：**页级转录/翻译那一段 prompt 前缀的逐字节复制**（稳定前缀 + 第 1..T 页全文，
    见 `understanding_service._page_context_head`）。放在最前面，解读调用才能命中该路的前缀缓存、
    并且模型手里就是整篇全文（用户口径："分别完全命中这两路模型的缓存，确保完整的记忆"）。

    `task_block`：解读的任务说明。**放在 head 之后**（不能塞进 system —— 那样 system 就与页级
    不同了，整段前缀缓存全作废），并明确"任务已经切换，忽略 system 里的页面 JSON 契约"。
    """
    label = "英文材料清单（原文转录，按论文顺序）"
    out: list[str] = []
    if head:
        out += [head, "",
                "==== 以上是这篇论文**全部页面**的完整前文（与页级转录/翻译同源，已被前缀缓存） ====",
                "【任务已切换】不要再输出 original_md / translation_md / breaks 那套页面 JSON —— "
                "下面改为**基于你上面已经通读过的整篇论文**做解读。",
                ""]
        if task_block:
            out += ["【解读任务说明】", task_block.strip(), ""]
    #: ⚠️ 这里一个"chunk"都不要出现：模型会把它抄进正文（用户口径 2026-11-28）。
    #: 清单被描述成"论文的段落条目、每条行首一个编号"，与它要写的 [A023] 同构。
    out += [f"【论文】{title}", f"【{label}】共 {len(inventory)} 条，按论文顺序：",
            "（每条行首是它的**编号**（`A001` 起，正文里按引用规则写成 `[编号]`）；"
            "正文条目给开头若干字作预览，表格与公式条目给全文数值/公式。预览被截断只是省篇幅，"
            "**不代表论文里没有这些内容** —— 不要据此说「材料缺失 / 表格数值被截断 / 无法核验」。）",
            ""]
    for item in inventory:
        line = f"[{item['code']}] {item['chunk_type']}"
        if item.get("page"):
            line += f" p{item['page']}"
        if item.get("section"):
            line += f" · {item['section']}"
        out.append(line)
        if item.get("image"):
            #: 只在这一条**真的能贴图**时才给短码：模型据此判断"这张能放进解读"；
            #: 没这一行的条目写 `img:…` 会被渲染侧丢掉（见 clean_image_refs）。
            out.append(f"    〔可插入的图：img:{item['code']}〕")
        full = (item.get("content") or "").strip()
        preview = (item.get("preview") or "").strip().replace("\n", " ")
        if full:                      # 表格/公式：给全文（数值网格不切）
            body = full.replace("\n", " ")
            cut = len(body) > RICH_CHARS
            out.append(f"    {body[:RICH_CHARS]}{' …（表格/公式正文截断）' if cut else ''}")
        elif preview:
            cut = len(preview) > PREVIEW_CHARS
            out.append(f"    {preview[:PREVIEW_CHARS]}{' …' if cut else ''}")
    if brief:
        out += ["", "【文档简报（术语与主题，供参考）】", brief]
    out += ["", "请按上面的【解读任务说明】输出：先自由 Markdown，最后用一个 ```json 代码块给出 refs。"]
    return "\n".join(out)
